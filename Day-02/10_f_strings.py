#Without an f-string:
name = "Mohamed"
age = 32
print("My name is " + name + " and I am " + str(age) + " years old.")

#With an f-string:
name = "Mohamed"
age = 32
print(f"My name is {name} and I am {age} years old.")

number_1 = 10
number_2 = 5
print(f"Sum: {number_1 + number_2}")
print(f"Difference: {number_1 - number_2}")
print(f"Product: {number_1 * number_2}")