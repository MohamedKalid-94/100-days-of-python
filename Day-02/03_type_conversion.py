#String → Integer
age_text = "32"
age = int(age_text)
print(age)
print(type(age))

#String → Float
price_text = "99.99"
price = float(price_text)
print(price)
print(type(price))

#Integer → String
score = 95
score_text = str(score)
print(score_text)
print(type(score_text))

#Integer → Float
number = 10
decimal_number = float(number)
print(decimal_number)

#Float → Integer
price = 99.99
price_as_integer = int(price)
print(price_as_integer)