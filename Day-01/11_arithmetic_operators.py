number_1 = 20
number_2 = 6

# Addition
print(number_1 + number_2)

# Subtraction
print(number_1 - number_2)

# Multiplication
print(number_1 * number_2)

# Division
print(number_1 / number_2)

# Floor division
print(number_1 // number_2)

# Remainder
print(number_1 % number_2)

# Power
print(number_1 ** 2)