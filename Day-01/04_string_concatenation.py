# Concatenation means joining strings together.
first_name = "Mohamed"
last_name = "Kalid"

full_name = first_name + " " + last_name
print(full_name)

# Another example
city = "Chennai"
country = "India"

location = city + ", " + country
print(location)

# We can also build a complete sentence.
age = 32

# age is an integer, so convert it to string before using +.

message = "My name is " + full_name + " and I am " + str(age) + " years old."
print(message)