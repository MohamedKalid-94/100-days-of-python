# A string is text enclosed inside quotes.

first_name = "Mohamed"
last_name = "Kalid"
programming_language = "Python"

print(first_name)
print(last_name)
print(programming_language)

# Strings can contain spaces and special characters.

message = "I am learning Python"
print(message)

# String indexing starts from 0.
language = "Python"
print(language[0])  # P
print(language[1])  # y
print(language[2])  # t
print(language[5])  # n

# Negative indexing starts from the end.
print(language[-1])  # n
print(language[-2])  # o